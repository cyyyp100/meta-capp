const DICT: Record<Lang, Record<string, string>> = { fr: FR, en: EN };

interface LangState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useLangStore = create<LangState>((set) => ({
  lang: localStorage.getItem("metacapp-lang") === "en" ? "en" : "fr",
  setLang: (l) => {
    localStorage.setItem("metacapp-lang", l);
    set({ lang: l });
    // La langue ne concerne pas que l'UI : le backend s'en sert pour les prompts
    // LLM. Sans cet appel, l'interface passe en anglais et Clikoda continue de
    // répondre en français. Best-effort : l'UI ne doit pas dépendre du réseau.
    void api.setBackendLang(l).catch(() => undefined);
  },
}));

function format(s: string, params?: Record<string, string | number>): string {
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}

export function useT(): (key: string, params?: Record<string, string | number>) => string {
  const lang = useLangStore((s) => s.lang);
  return (key, params) => format(DICT[lang][key] ?? DICT.fr[key] ?? key, params);
}
